export function activeOrbitxKols() {
  return ORBITX_KOLS.filter((k) => k.status === "active");
}

export function kolByAddress(address) {
  if (!address) return null;
  return ORBITX_KOLS.find((k) => k.address === address) || null;
}

export function isAssignedKol(address) {
  const row = kolByAddress(address);
  return Boolean(row && row.status === "active");
}

export function trackedRowsFromDirectory() {
  return activeOrbitxKols().map((k) => ({
    address: k.address,
    label: k.name,
    label_kind: "KOL",
    notes: k.twitter || "",
    created_by: "orbitx-directory",
  }));
}

export function kolWatchBatch(size = 8) {
  const list = activeOrbitxKols();
  if (!list.length) return [];
  const start = Math.floor(Date.now() / 45_000) % list.length;
  return Array.from({ length: Math.min(size, list.length) }, (_, i) => list[(start + i) % list.length].address);
}
