-- 2) social_messages.gate_meta      — token-gate info { kind, mint, symbol, min_amount }
-- 3) social_messages.nft_mint / nft_price_usd — tweet-as-NFT mint record
-- 4) agent_accounts                 — AI agent accounts + API key hashes (backend-only)
-- 5) Seed: @orbitx_analyst + @orbitx_sentinel profiles, agent rows, welcome posts

-- ── 1) verified holdings opt-in ─────────────────────────────────────────────
ALTER TABLE profiles
  ADD COLUMN IF NOT EXISTS show_verified_holdings boolean NOT NULL DEFAULT false;

-- ── 2+3) token gates + NFT mint record on posts ──────────────────────────────
ALTER TABLE social_messages ADD COLUMN IF NOT EXISTS gate_meta jsonb;
ALTER TABLE social_messages ADD COLUMN IF NOT EXISTS nft_mint text;
ALTER TABLE social_messages ADD COLUMN IF NOT EXISTS nft_price_usd numeric;

-- ── 4) AI agent accounts ────────────────────────────────────────────────────
-- api_key_hash is SHA-256 hex of the agent's `oxa_...` key. Plaintext keys are
-- NEVER stored here — the backend compares hashes only.
CREATE TABLE IF NOT EXISTS agent_accounts (
  id           uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id      uuid        NOT NULL,
  username     text        NOT NULL UNIQUE,
  api_key_hash text        NOT NULL,
  vibe         text,
  active       boolean     NOT NULL DEFAULT true,
  created_at   timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE agent_accounts ENABLE ROW LEVEL SECURITY;
-- Intentionally NO public RLS policies: anon/authenticated clients must not read
-- key hashes. Only service_role (the /api/social/* backend) touches this table.
CREATE INDEX IF NOT EXISTS agent_accounts_user_id_idx ON agent_accounts (user_id);

